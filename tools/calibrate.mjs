// Calibrates per-soldier damage per level so an average player's boss dies right at 100%.
// Plays every level with the average bot (boss unbreakable), measures the raw damage the squad
// has put into the boss by the moment it arrives (100%), and scales that level's damage so the
// median of those equals the boss's HP. Enemy and crate HP scale with the same number, so the
// road plays the same; only the boss race moves. Usage: node tools/calibrate.mjs [--write] [seeds]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const H = require('./headless.cjs');

const WRITE = process.argv.includes('--write');
const SEEDS = +(process.argv.find(a => /^\d+$/.test(a)) || 8);
const AVG = { pBest: 0.7, pPump: 0.5, pDodge: 0.7 };
const api = H.loadGame();
// the weapon an average player carries into level L: the middle crate of the level before
export const expWeapon = L => (L <= 1 ? 1 : Math.min(10, api.ctx.crateTier(L - 1, 1)));
const median = a => { const s = a.slice().sort((x, y) => x - y); return s[s.length >> 1]; };

function measure(L) {
  const out = [];
  for (let s = 1; s <= SEEDS; s++) {
    const r = H.playLevel(api, { L, seed: 100 + s, prof: AVG, up: { rate: 0, dmg: 0, rev: 0 }, weapon: expWeapon(L), noBreak: true, stopAtClash: true });
    out.push(r.bossDmg);
  }
  return median(out);
}

const table = {};
for (let L = 1; L <= 40; L++) {
  let dmg = api.dmgPerSoldier ? api.dmgPerSoldier(L) : api.levelTuning(L).dmg;
  for (let pass = 0; pass < 3; pass++) {
    api.TUNING[L] = { dmg };
    const got = measure(L), want = api.bossHP(L);
    const k = want / Math.max(1e-9, got);
    dmg *= Math.min(4, Math.max(0.25, k));
    if (Math.abs(k - 1) < 0.04) break;
  }
  api.TUNING[L] = { dmg };
  table[L] = { dmg: +dmg.toPrecision(4) };
  console.log(`L${String(L).padEnd(3)} boss ${String(api.bossHP(L)).padStart(5)}  dmg/shot ${dmg.toFixed(3)}  weapon Lv${expWeapon(L)}`);
}
if (WRITE) {
  const f = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'js', '15-tables.js');
  const body = Object.entries(table).map(([L, v]) => `  ${L}: { dmg: ${v.dmg} },`).join('\n');
  fs.writeFileSync(f, `// Generated by \`node tools/calibrate.mjs --write\`. Per-level per-soldier damage, set so an average player kills the boss right at 100%.\nObject.assign(TUNING, {\n${body}\n});\n`);
  console.log('wrote', f);
}
