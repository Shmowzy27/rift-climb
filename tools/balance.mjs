// Runs the in-game balance check under node and prints the per-level table.
// Usage: node tools/balance.mjs
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const M = require('../src/js/10-balance.js');
// the archetype table lives in the content file; pull just that object for the report
import { readFileSync as rf } from 'node:fs';
const contentSrc = rf(new URL('../src/js/20-content.js', import.meta.url), 'utf8');
const ARCH = new Function(contentSrc.slice(contentSrc.indexOf('const ARCH = {'), contentSrc.indexOf('const ARCH_ORDER')) + '; return ARCH;')();
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const TABLES = new URL('../src/js/15-tables.js', import.meta.url);

if (process.argv.includes('--write')) {
  // calibrate each level's gate gap so a careless player lands at ~21s (a near miss)
  for (let L = 1; L <= 40; L++) {
    const st = M.stageOf(L);
    let gap = M.BAL.gateGap[st - 1] * 6 / M.gateSetsFor(L);
    if (!M.isStageBoss(L)) {
      let lo = 0.003, hi = 0.45, best = null;
      for (let i = 0; i < 12; i++) {
        const m = +((lo + hi) / 2).toFixed(4);
        M.TUNING[L] = { gap: m }; M.clearTuningCache();
        const t = M.levelTuning(L, true).tCareless, tt = isFinite(t) ? t : 99;
        if (!best || Math.abs(tt - 21) < best.err) best = { gap: m, err: Math.abs(tt - 21) };
        if (tt < 21) lo = m; else hi = m;
      }
      gap = best.gap;
    }
    M.TUNING[L] = { gap: +gap.toFixed(4) }; M.clearTuningCache();
    const t = M.levelTuning(L, true);
    M.TUNING[L] = { gap: +gap.toFixed(4), dmg: t.dmg, baseHP: t.baseHP };
    process.stdout.write(`L${L} `);
  }
  writeFileSync(TABLES, '// Generated by `node tools/balance.mjs --write`. Per-level gate gap, per-soldier damage, base HP.\nObject.assign(TUNING, ' + JSON.stringify(M.TUNING) + ');\n');
  console.log('\nwrote src/js/15-tables.js');
}
if (existsSync(TABLES)) Object.assign(M.TUNING, JSON.parse(readFileSync(TABLES, 'utf8').match(/Object\.assign\(TUNING, (.*)\);/)[1]));
M.clearTuningCache();

const pad = (s, n) => String(s).padStart(n);
console.log('RIFT CLIMB balance check: average player 13-15s, careless player 19-23s (base timer 20s)');
console.log(' L  boss  enemyHP  dmg/soldier  avgSquad  carelessSquad    baseHP    avg T   careless T');
let bad = 0;
for (const r of M.balanceCheck()) {
  const boss = M.isStageBoss(r.L);
  // bosses get 3x HP and a 55s timer: check the same 6s-spare / near-miss shape scaled to the timer
  const okA = boss ? r.tAvg <= r.timer - 5 : r.tAvg >= 13 && r.tAvg <= 15;
  const okC = boss ? r.tCareless > r.timer : r.tCareless >= 19 && r.tCareless <= 23;
  if (!okA || !okC) bad++;
  console.log(`${pad(r.L, 2)}  ${boss ? 'BOSS' : '    '} ${pad(M.enemyHP(r.L), 7)}  ${pad(r.dmg, 10)}  ${pad(r.Na, 8)}  ${pad(r.Nc, 13)}  ${pad(r.baseHP, 9)}  ${pad(r.tAvg.toFixed(1), 6)}s  ${pad(isFinite(r.tCareless) ? r.tCareless.toFixed(1) : 'never', 9)}s ${okA && okC ? '' : ' <-- OUT'}`);
}
console.log(`\nout-of-band levels: ${bad}`);

// gate rule check: best vs second within 25%, mixed op types, results >= 1
let viol = 0, total = 0;
const r = M.rng(7);
for (let L = 1; L <= 40; L++) for (const N of [6, 10, 37, 120, 640, 2500]) for (let i = 0; i < 25; i++) {
  const g = M.makeGateSet(N, L, r); total++;
  const res = g.map(x => x.result).sort((a, b) => b - a);
  if (res[0] / res[1] > 1.25 || res[1] >= res[0]) viol++;
}
console.log(`gate sets checked: ${total}, violating the 25% rule: ${viol}`);
for (const L of [3, 12, 20, 28, 36]) {
  const g = M.makeGateSet(48, L, r);
  console.log(`  L${L} with 48 soldiers: ` + g.map(x => `[${x.label.join(' ')}] -> ${x.result}`).join('  |  '));
}

// base assault, re-run per stage with its weapon archetype (Stage 5: all four)
console.log('\nBase assault per archetype (avg 13-15s, careless 19-23s; bosses: avg < timer-5, careless > timer)');
console.log(' L  squad      rate  dmg/soldier     baseHP   avg DPS    avg T   careless T');
let badA = 0;
for (let L = 1; L <= 40; L++) {
  const st = M.stageOf(L);
  const archs = st === 5 ? ['crossbow', 'staff', 'blade', 'beam'] : [['crossbow', 'staff', 'blade', 'beam'][st - 1]];
  if (!(L % 4 === 1 || M.isStageBoss(L) || L >= 33)) continue; // sample: every 4th level, all bosses, all of the Rift
  for (const a of archs) {
    const r = M.archBaseRow(L, ARCH[a], st === 5);
    const boss = M.isStageBoss(L), timer = boss ? 55 : 20;
    const ok = boss ? r.tAvg <= timer - 5 && r.tCareless > timer : r.tAvg >= 13 && r.tAvg <= 15 && r.tCareless >= 19 && r.tCareless <= 23;
    if (!ok) badA++;
    console.log(`${pad(L, 2)}  ${a.padEnd(9)} ${pad(r.rate, 5)} ${pad(r.dmgPerSoldier, 12)} ${pad(r.baseHP, 10)} ${pad(r.avgDPS, 9)} ${pad(r.tAvg.toFixed(1), 7)}s ${pad(isFinite(r.tCareless) ? r.tCareless.toFixed(1) : 'never', 10)}s${ok ? '' : '  <-- OUT'}`);
  }
}
console.log(`archetype rows out of band: ${badA}`);
process.exitCode = bad || viol || badA ? 1 : 0;
